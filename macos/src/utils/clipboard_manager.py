"""Qt clipboard helpers used by selection and safe insertion flows."""

from __future__ import annotations

import logging
from dataclasses import dataclass

from PySide6.QtCore import QByteArray, QMimeData, QThread
from PySide6.QtWidgets import QApplication

from src.utils.logger import log


try:
    from AppKit import NSPasteboard, NSPasteboardTypeString
except ImportError:  # Allows the macOS source tests to run on other hosts.
    NSPasteboard = None
    NSPasteboardTypeString = "public.utf8-plain-text"
try:
    from AppKit import NSPasteboardContentsCurrentHostOnly
except ImportError:
    NSPasteboardContentsCurrentHostOnly = None
try:
    from Foundation import NSData
except ImportError:
    NSData = None


# nspasteboard.org markers honoured by clipboard history managers (Maccy,
# Paste, Raycast, Alfred...). The sentinel and the answer written only to
# drive SuperMenu's own Command+C / Command+V round trip are neither recorded
# nor displayed. Qt exports custom MIME types under its own UTI prefix, never
# under these raw identifiers, hence the native write below.
INTERNAL_PASTEBOARD_MARKERS = (
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
)


def _write_internal_text(text: str) -> bool:
    """Write ``text`` with the transient markers; False when AppKit fails."""
    if NSPasteboard is None:
        return False
    try:
        pasteboard = NSPasteboard.generalPasteboard()
        if pasteboard is None:
            return False
        prepare = getattr(pasteboard, "prepareForNewContentsWithOptions_", None)
        if callable(prepare) and NSPasteboardContentsCurrentHostOnly is not None:
            # Also keeps Universal Clipboard from offering it to other devices.
            prepare(NSPasteboardContentsCurrentHostOnly)
        else:
            pasteboard.clearContents()
        if not pasteboard.setString_forType_(text, NSPasteboardTypeString):
            return False
        marker = NSData.data() if NSData is not None else b""
        for marker_type in INTERNAL_PASTEBOARD_MARKERS:
            # A refused marker only costs the history hint, not the paste.
            pasteboard.setData_forType_(marker, marker_type)
        return True
    except Exception as exc:
        log(
            f"Écriture native du presse-papiers impossible : {exc}",
            logging.DEBUG,
        )
        return False


@dataclass
class ClipboardSnapshot:
    formats: dict[str, bytes]

    def restore(self) -> bool:
        app = QApplication.instance()
        if app is None or QThread.currentThread() is not app.thread():
            return False
        mime_data = QMimeData()
        for mime_format, data in self.formats.items():
            mime_data.setData(mime_format, QByteArray(data))
        app.clipboard().setMimeData(mime_data)
        return True


class ClipboardManager:
    @staticmethod
    def get_clipboard_text_safe() -> str:
        app = QApplication.instance()
        if app is None or QThread.currentThread() is not app.thread():
            return ""
        return app.clipboard().text() or ""

    @staticmethod
    def set_clipboard_text_safe(text: str) -> bool:
        """Write an internal, transient value: the sentinel or an answer.

        The native write carries the history markers; the Qt write remains
        the fallback whenever AppKit is unavailable or refuses the value.
        """
        app = QApplication.instance()
        if app is None or QThread.currentThread() is not app.thread():
            return False
        text = str(text)
        # The sentinel check and the restore both read through Qt: keep the
        # native write only once Qt is seen to read it back unchanged.
        if _write_internal_text(text) and (app.clipboard().text() or "") == text:
            return True
        app.clipboard().setText(text)
        return True

    @staticmethod
    def capture_snapshot() -> ClipboardSnapshot:
        app = QApplication.instance()
        if app is None or QThread.currentThread() is not app.thread():
            return ClipboardSnapshot({})
        mime_data = app.clipboard().mimeData()
        return ClipboardSnapshot(
            {
                mime_format: bytes(mime_data.data(mime_format))
                for mime_format in mime_data.formats()
            }
        )

    @staticmethod
    def restore_if_unchanged(
        snapshot: ClipboardSnapshot | None,
        expected_text: str,
    ) -> bool:
        if snapshot is None:
            return False
        if ClipboardManager.get_clipboard_text_safe() != expected_text:
            return False
        return snapshot.restore()
